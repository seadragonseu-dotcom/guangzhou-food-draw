# =====================================================
# Generate Relation
# =====================================================


def build_relation(
        restaurants,
        dishes
):


    relations=[]


    for index,dish in enumerate(
        dishes,
        start=30001
    ):


        restaurant = restaurants[

            index %

            len(restaurants)

        ]


        relations.append({

            "id":

                index,

            "restaurant_id":

                restaurant["id"],

            "dish_id":

                dish["id"],

            "meal":

                dish["meal"],

            "tags":

                "情侣,广州特色",

            "reason":

                f"{restaurant['name']}特色推荐"

        })


    return relations





# =====================================================
# Export Excel
# =====================================================


def export_excel(
        restaurants,
        dishes,
        relations
):


    DATABASE_FILE.parent.mkdir(

        exist_ok=True

    )


    with pd.ExcelWriter(

        DATABASE_FILE,

        engine="openpyxl"

    ) as writer:


        pd.DataFrame(

            restaurants

        ).to_excel(

            writer,

            sheet_name="restaurants",

            index=False

        )


        pd.DataFrame(

            dishes

        ).to_excel(

            writer,

            sheet_name="dishes",

            index=False

        )


        pd.DataFrame(

            relations

        ).to_excel(

            writer,

            sheet_name="food_relation",

            index=False

        )





